    const dictionaries = { ar, en };
    const listeners = [];
    let lang = 'ar';
    try {
        const stored = localStorage.getItem(STORAGE_KEY);
        const fromQuery = new URLSearchParams(location.search).get('lang');
        lang = dictionaries[fromQuery] ? fromQuery : dictionaries[stored] ? stored : 'ar';
    } catch (error) {
        lang = 'ar';
    }

    function t(key, vars = {}) {
        const text = (dictionaries[lang][key] ?? dictionaries.ar[key] ?? key);
        return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ''));
    }

    // Shows a translated text and remembers the key for later language switches.
    function setText(element, key, vars) {
        if (!element) return;
        element.dataset.i18n = key;
        if (vars) element.dataset.i18nVars = JSON.stringify(vars);
        else delete element.dataset.i18nVars;
        element.textContent = t(key, vars);
    }

    // A server reply's error key, or a fallback key.
    function errorKey(response, fallbackKey) {
        const key = response && response.error ? `err.${response.error}` : null;
        return key && dictionaries.ar[key] ? key : fallbackKey;
    }

    function apply(root = document) {
        document.documentElement.lang = lang;
        document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
        root.querySelectorAll('[data-i18n]').forEach((el) => {
            let vars;
            try { vars = el.dataset.i18nVars ? JSON.parse(el.dataset.i18nVars) : undefined; } catch { vars = undefined; }
            el.textContent = t(el.dataset.i18n, vars);
        });
        root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
            el.placeholder = t(el.dataset.i18nPlaceholder);
        });
        root.querySelectorAll('[data-i18n-title]').forEach((el) => {
            el.title = t(el.dataset.i18nTitle);
            el.setAttribute('aria-label', el.title);
        });
    }

    function setLang(next) {
        if (!dictionaries[next] || next === lang) return;
        lang = next;
        try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* storage unavailable */ }
        apply();
        listeners.forEach((listener) => listener(lang));
    }

    window.LabShowI18n = {
        t, setText, errorKey, apply, setLang,
        toggle: () => setLang(lang === 'ar' ? 'en' : 'ar'),
        onChange: (listener) => listeners.push(listener),
        get lang() { return lang; },
        dictionaries
    };
